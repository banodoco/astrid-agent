#!/usr/bin/env python3
"""Render the timeline edit flag reference from the current parser and SDK registry."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from astrid.sdk.timeline.commands import flag_inventory_table
from tools.parity.inventory import DEFAULT_ROOT, build_inventory


TARGET = DEFAULT_ROOT / "astrid/packs/timeline/docs/references/edit-command-flags.md"
FIXTURE = DEFAULT_ROOT / "tests/parity/edit-command-flags.json"


def canonical_rows() -> list[dict[str, object]]:
    rows = flag_inventory_table(build_inventory(DEFAULT_ROOT))
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    if rows != fixture:
        raise RuntimeError(
            "current parser/SDK flag rows differ from tests/parity/edit-command-flags.json; "
            "update the parity fixture through its existing workflow first"
        )
    return rows


def render_reference(rows: list[dict[str, object]] | None = None) -> str:
    rows = canonical_rows() if rows is None else rows
    grouped: dict[str, list[str]] = {}
    for row in rows:
        options = grouped.setdefault(str(row["operation"]), [])
        for flag in row["flags"]:
            if flag not in options:
                options.append(flag)

    lines = [
        "# Timeline edit flags",
        "",
        "<!-- Generated by `python3 -m tools.parity.edit_flag_reference`; do not edit by hand. -->",
        "",
        "Each option maps to the existing OpCall operation. Use `timelines edit --help` for values and argument details.",
        "",
        "| Operation | Flags |",
        "| --- | --- |",
    ]
    for operation, options in sorted(grouped.items()):
        rendered = ", ".join(f"`{flag}`" for flag in options)
        lines.append(f"| `{operation}` | {rendered} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated reference is stale")
    args = parser.parse_args(argv)

    rows = canonical_rows()
    expected = render_reference(rows)
    options_count = sum(len(row["flags"]) for row in rows)
    operations_count = len({str(row["operation"]) for row in rows})
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != expected:
            print(f"stale generated reference: {TARGET}", file=sys.stderr)
            return 1
        print(f"verified {TARGET.relative_to(DEFAULT_ROOT)} ({options_count} options, {operations_count} operations)")
        return 0

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(DEFAULT_ROOT)} ({options_count} options, {operations_count} operations)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

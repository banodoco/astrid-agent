"""A delivered generation names one link that opens its project in Astrid."""
import hashlib
from types import SimpleNamespace

from astrid.core.generation.delivery import deliver_generation


def _managed_result(tmp_path, *, row_project):
    data = b'\x89PNG generated bytes'
    digest = hashlib.sha256(data).hexdigest()
    local = tmp_path / 'runtime-object.png'
    local.write_bytes(data)
    row = {'object_id': 'obj-1', 'digest': f'sha256:{digest}', 'size': len(data),
           'role': 'result', 'filename': 'first.png'}
    if row_project is not None:
        row['project_id'] = row_project
    client = SimpleNamespace(media=SimpleNamespace(open=lambda *a, **k: SimpleNamespace(
        ok=True, data={'local_path': str(local)}, error=None)))
    result = {'task_id': 'task-1', 'manifest': {'outputs': [row]}}
    return result, client


def test_completed_generation_result_carries_open_url_for_its_project(tmp_path):
    result, client = _managed_result(tmp_path, row_project='proj-1')

    delivered = deliver_generation(result, client=client, out=tmp_path / 'out')

    assert delivered['open_url'] == 'https://astrid.haus/tools/video-editor?project=proj-1'


def test_open_url_uses_the_project_the_generation_was_given_when_output_names_none(tmp_path):
    result, client = _managed_result(tmp_path, row_project=None)

    delivered = deliver_generation(result, client=client, out=tmp_path / 'out', project='proj-2')

    assert delivered['open_url'] == 'https://astrid.haus/tools/video-editor?project=proj-2'

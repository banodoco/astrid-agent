import copy
import importlib.util
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('freshness', ROOT / 'scripts/ci/freshness.py')
f = importlib.util.module_from_spec(spec)
spec.loader.exec_module(f)
SCHEMA = {'type': 'object', 'required': ['version', 'repos', 'generated', 'toolchain', 'created_at']}


class FreshnessTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.installed = Path(self.tmp.name) / 'installed.json'
        self.archive = Path(self.tmp.name) / 'installed.tgz'
        self.archive.write_bytes(b'archive')
        self.vibe = 'a' * 40
        self.write_installed(self.vibe)
        self.tuple = {'version': 1, 'name': 'CP1', 'repos': {r: {'url': 'https://github.com/banodoco/astrid-' + r, 'sha': s} for r, s in f.CP1.items()}, 'generated': {}, 'toolchain': {}, 'created_at': '2026-10-31T23:36:50Z'}
        self.files = {}
        self.put('runtime', 'contract/artifacts.json', {'producer': 'astrid-runtime', 'version': 'runtime-version', 'artifacts': {'src': 'sha256:' + f.digest(b'good')}})
        self.put('runtime', 'src', b'good')
        self.put('agent', 'artifacts.json', {'producer': 'astrid-agent', 'version': 'agent-version', 'artifacts': {'src': 'sha256:' + f.digest(b'agent')}})
        self.put('agent', 'src', b'agent')
        self.put('agent', 'generated', b'good')
        self.put('app', 'generated', b'good')
        self.put('app', 'agent-generated', b'agent')
        self.put('agent', 'runtime.lock.json', self.lock('runtime', 'contract/artifacts.json', 'runtime-version', 'generated', 'good'))
        self.put('app', 'runtime.lock.json', self.lock('runtime', 'contract/artifacts.json', 'runtime-version', 'generated', 'good'))
        self.put('app', 'config/astrid-cli-surface/vendor.lock.json', self.lock('agent', 'artifacts.json', 'agent-version', 'agent-generated', 'agent'))
        self.put('app', 'public/install-manifest.json', {'agent': {'sha': f.CP1['agent']}, 'runtime': {'sha': f.CP1['runtime']}})
        self.put('agent', 'astrid/packs/vibecomfy/pins.json', {'sources': {'vibecomfy': {'revision': self.vibe}}})
        self.put('agent', 'astrid/packs/vibecomfy/recipe.windows-cu130.json', {'pins': {'path': 'packs/vibecomfy/pins.json', 'sha256': f.digest(self.files['agent', 'astrid/packs/vibecomfy/pins.json'])}, 'source_bindings': [{'name': 'vibecomfy', 'pin': 'vibecomfy'}]})
        self.put('agent', 'remotion/artifacts/banodoco-timeline-composition-0.0.17.tgz', b'archive')
        self.put('app', 'vendor/artifacts/banodoco-timeline-composition-0.0.17.tgz', b'archive')

    def write_installed(self, vibe):
        self.installed.write_text(json.dumps({'agent': {'sha': f.CP1['agent']}, 'runtime': {'sha': f.CP1['runtime']}, 'vibecomfy': {'sha': vibe}}))

    def lock(self, producer, manifest, version, dest, content):
        return {'producer': 'astrid-' + producer, 'source_commit': f.CP1[producer], 'manifest': manifest, 'producer_version': version, 'files': {dest: {'from': 'src', 'sha256': 'sha256:' + f.digest(content.encode())}}}

    def put(self, repo, path, value):
        self.files[repo, path] = value if isinstance(value, bytes) else json.dumps(value).encode()

    def run_check(self, tup=None, vibe=None):
        def read(_repos, repo, path):
            if (repo, path) not in self.files:
                raise FileNotFoundError(path)
            return self.files[repo, path]
        def fake_git(_repo, *args):
            if args[0] == 'rev-parse':
                return (vibe or self.vibe).encode()
            return b''
        with patch.object(f, 'read_git', side_effect=read), patch.object(f, 'git', side_effect=fake_git), patch.object(f, 'COMPOSITION', f.digest(b'archive')):
            return f.evaluate(tup or self.tuple, SCHEMA, {r: r for r in f.CP1}, self.installed, 'installed-vibe', self.archive)

    def assert_red(self, text, **kwargs):
        result = self.run_check(**kwargs)
        self.assertEqual(result['result'], 'fail', result)
        self.assertIn(text, str(result['errors']))

    def test_clean_synthetic_and_tuple_digest(self):
        result = self.run_check()
        self.assertEqual(result['result'], 'pass', result)
        self.assertEqual(result['tuple_digest'], f.tuple_digest(self.tuple))
        self.assertEqual(result['expected_findings'], [])

    def test_stale_generated_bytes(self):
        self.put('agent', 'generated', b'broken')
        self.assert_red('stale generated bytes')

    def test_source_commit_differs(self):
        lock = self.lock('runtime', 'contract/artifacts.json', 'runtime-version', 'generated', 'good')
        lock['source_commit'] = 'b' * 40
        self.put('agent', 'runtime.lock.json', lock)
        self.assert_red('source_commit')

    def test_wrong_agent_app_relationship(self):
        lock = self.lock('agent', 'artifacts.json', 'agent-version', 'agent-generated', 'agent')
        lock['source_commit'] = 'b' * 40
        self.put('app', 'config/astrid-cli-surface/vendor.lock.json', lock)
        self.assert_red('source_commit')

    def test_wrong_composition_and_missing(self):
        self.put('app', 'vendor/artifacts/banodoco-timeline-composition-0.0.17.tgz', b'wrong')
        self.assert_red('composition archive digest')
        del self.files['agent', 'remotion/artifacts/banodoco-timeline-composition-0.0.17.tgz']
        self.assert_red('composition archive missing')
        self.archive.write_bytes(b'wrong')
        self.assert_red('installed composition archive digest')

    def test_installer_rewrites_vibecomfy(self):
        self.write_installed('b' * 40)
        self.assert_red('installed manifest VibeComfy')
        self.write_installed(self.vibe)
        self.assert_red('installed VibeComfy checkout', vibe='b' * 40)

    def test_cp1_exception_is_exact_and_visible(self):
        app_lock = self.lock('runtime', 'contract/artifacts.json', 'runtime-version', 'generated', 'good')
        app_lock['source_commit'] = 'b' * 40
        self.put('app', 'runtime.lock.json', app_lock)
        self.put('app', 'public/install-manifest.json', {'agent': {'sha': 'c' * 40}, 'runtime': {'sha': 'd' * 40}})
        hashes = {path: f.digest(self.files['app', path]) for path in f.EXCEPTIONS}
        with patch.object(f, 'EXCEPTIONS', hashes):
            result = self.run_check()
            self.assertEqual(result['result'], 'pass', result)
            self.assertEqual(len(result['expected_findings']), 3)
            self.assertTrue(all('stale' in x and 'I-AP-07' in x for x in result['expected_findings']))
            self.put('app', 'public/install-manifest.json', {'agent': {'sha': 'e' * 40}, 'runtime': {'sha': 'd' * 40}})
            self.assert_red('install-manifest agent.sha')

    def test_missing_evidence_and_wrong_tuple(self):
        del self.files['agent', 'generated']
        self.assert_red('evidence unavailable')
        bad = copy.deepcopy(self.tuple)
        bad['repos']['runtime']['sha'] = 'b' * 40
        self.assert_red('not the published', tup=bad)


if __name__ == '__main__':
    unittest.main()

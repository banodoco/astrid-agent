from __future__ import annotations

import os
import tarfile
from pathlib import Path

import pytest

from tests.packs.rendering._helpers import (
    _extract_private_tarball,
    _stage_private_node_modules,
)


def _entries(root: Path) -> dict[str, tuple[str, bytes | str | None]]:
    result: dict[str, tuple[str, bytes | str | None]] = {}

    def visit(directory: Path) -> None:
        for entry in sorted(os.scandir(directory), key=lambda item: item.name):
            path = Path(entry.path)
            relative = str(path.relative_to(root))
            if entry.is_dir(follow_symlinks=False):
                result[relative] = ("dir", None)
                visit(path)
            elif entry.is_symlink():
                result[relative] = ("link", os.readlink(path))
            else:
                result[relative] = ("file", path.read_bytes())

    visit(root)
    return result


def test_private_staging_uses_real_scopes_and_is_idempotent(tmp_path: Path) -> None:
    borrowed = tmp_path / "borrowed" / "node_modules"
    (borrowed / "@scope" / "leaf").mkdir(parents=True)
    (borrowed / "@scope" / "leaf" / "package.json").write_bytes(b"leaf")
    (borrowed / "plain").mkdir()
    (borrowed / "plain" / "package.json").write_bytes(b"plain")
    stage = tmp_path / "stage" / "node_modules"
    owned = stage / "@banodoco" / "timeline-composition"
    owned.mkdir(parents=True)
    (owned / "package.json").write_bytes(b"published-package")

    _stage_private_node_modules(borrowed, stage, skip_scopes={"@banodoco"})
    before_borrowed = _entries(borrowed)
    _stage_private_node_modules(borrowed, stage, skip_scopes={"@banodoco"})

    assert (stage / "@scope").is_dir() and not (stage / "@scope").is_symlink()
    assert (stage / "@scope" / "leaf").is_symlink()
    assert (stage / "@scope" / "leaf").resolve() == (borrowed / "@scope" / "leaf").resolve()
    assert (stage / "plain").is_symlink()
    assert (owned / "package.json").read_bytes() == b"published-package"
    assert _entries(borrowed) == before_borrowed
    assert not (borrowed / "@scope" / "leaf" / "leaf").exists()


def test_private_staging_rejects_linked_scope_parent_before_writing(tmp_path: Path) -> None:
    borrowed = tmp_path / "borrowed" / "node_modules"
    (borrowed / "@scope" / "leaf").mkdir(parents=True)
    (borrowed / "@scope" / "leaf" / "package.json").write_bytes(b"leaf")
    stage = tmp_path / "stage" / "node_modules"
    stage.mkdir(parents=True)
    (stage / "@scope").symlink_to(borrowed / "@scope", target_is_directory=True)
    before_borrowed = _entries(borrowed)

    with pytest.raises(ValueError, match="borrowed graph"):
        _stage_private_node_modules(borrowed, stage)

    assert _entries(borrowed) == before_borrowed
    assert not (borrowed / "@scope" / "leaf" / "leaf").exists()


def test_private_tar_extract_rejects_linked_scope_before_writing(tmp_path: Path) -> None:
    borrowed = tmp_path / "borrowed" / "node_modules"
    (borrowed / "@scope" / "leaf").mkdir(parents=True)
    (borrowed / "@scope" / "leaf" / "package.json").write_bytes(b"shared")
    archive = tmp_path / "package.tgz"
    payload = tmp_path / "payload"
    (payload / "package").mkdir(parents=True)
    (payload / "package" / "new.txt").write_bytes(b"must-not-land")
    with tarfile.open(archive, "w:gz") as target:
        target.add(payload / "package", arcname="package")

    stage = tmp_path / "stage" / "node_modules"
    stage.mkdir(parents=True)
    (stage / "@scope").symlink_to(borrowed / "@scope", target_is_directory=True)
    before_borrowed = _entries(borrowed)

    with pytest.raises(ValueError, match="borrowed graph"):
        _extract_private_tarball(archive, stage / "@scope", borrowed=borrowed)

    assert _entries(borrowed) == before_borrowed
    assert not (borrowed / "@scope" / "new.txt").exists()

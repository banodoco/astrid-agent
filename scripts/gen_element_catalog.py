#!/usr/bin/env python3
"""Generate the editor-facing Astrid element catalog projection."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from astrid.core.element.catalog import (  # noqa: E402
    EDITOR_CATALOG_VERSION,
    _clear_registry_cache,
    list_element_descriptors,
)
from astrid.core.element.registry import load_default_registry  # noqa: E402
from scripts.gen_effect_registry import _public_registry_ids  # noqa: E402

DEFAULT_OUTPUT = REPO_ROOT / "astrid" / "packs" / "rendering" / "elements" / "catalog.ts"

BANNER = """// DO NOT EDIT — generated by scripts/gen_element_catalog.py.
//
// Astrid's element registry and renderers remain authoritative. This file is
// the deterministic, data-only projection imported by editor hosts such as
// Astrid App; regenerate it when an element manifest or component changes.
"""


def generate() -> str:
    # The shipped projection is an artifact of the core rendering pack. Other
    # selected packs remain available through the live registry, but their
    # presence or health cannot change this generated file.
    _clear_registry_cache()
    core_skips = [
        record for record in load_default_registry().diagnostics
        if record.pack_id == "rendering"
    ]
    if core_skips:
        raise ValueError(
            "Cannot generate an incomplete core element catalog:\n"
            + "\n".join(str(record) for record in core_skips)
        )
    descriptors = list_element_descriptors(include_shadowed=True, pack_id="rendering")
    descriptors = _preserve_public_renderability(descriptors)
    payload = json.dumps(descriptors, indent=2, sort_keys=True, ensure_ascii=False)
    return "\n".join(
        (
            BANNER.rstrip(),
            "",
            f"export const ASTRID_ELEMENT_CATALOG_VERSION = {EDITOR_CATALOG_VERSION} as const;",
            "",
            "export type AstridRenderingElementKind = 'effect' | 'animation' | 'transition';",
            "",
            "export type AstridRenderingElementParameter = {",
            "  name: string;",
            "  label: string;",
            "  description: string;",
            "  type: 'number' | 'select' | 'boolean' | 'color' | 'audio-binding';",
            "  default?: number | string | boolean;",
            "  min?: number;",
            "  max?: number;",
            "  step?: number;",
            "  options?: {label: string; value: string}[];",
            "};",
            "",
            "export type AstridRenderingElementDescriptor = {",
            "  id: string;",
            "  kind: AstridRenderingElementKind;",
            "  label: string;",
            "  description: string;",
            "  shortDescription: string;",
            "  keywords: string[];",
            "  defaults: Record<string, unknown>;",
            "  schema: Record<string, unknown>;",
            "  parameters: AstridRenderingElementParameter[];",
            "  source: string;",
            "  packId: string;",
            "  componentPath: string;",
            "  revision: string;",
            "  runtime: Record<string, unknown>;",
            "  renderability: {",
            "    preview: 'supported' | 'blocked' | 'unknown';",
            "    browserExport: 'supported' | 'blocked' | 'unknown';",
            "    workerExport: 'supported' | 'blocked' | 'unknown';",
            "  };",
            "};",
            "",
            "export const ASTRID_ELEMENT_CATALOG: readonly AstridRenderingElementDescriptor[] = Object.freeze(",
            payload,
            ");",
            "",
            "// Backwards-compatible name used by the editor integration.",
            "export const ASTRID_RENDERING_ELEMENTS = ASTRID_ELEMENT_CATALOG;",
            "",
            "export const ASTRID_EFFECT_CATALOG = ASTRID_ELEMENT_CATALOG.filter((element) => element.kind === 'effect');",
            "export const ASTRID_ANIMATION_CATALOG = ASTRID_ELEMENT_CATALOG.filter((element) => element.kind === 'animation');",
            "export const ASTRID_TRANSITION_CATALOG = ASTRID_ELEMENT_CATALOG.filter((element) => element.kind === 'transition');",
            "",
        )
    )


def _preserve_public_renderability(
    descriptors: tuple[dict[str, object], ...],
) -> tuple[dict[str, object], ...]:
    """Keep public Composition wrappers renderable after source deletion.

    The Agent registry retains the canonical descriptors for the nine bundled
    wrappers, while their executable implementations now live in Composition.
    Membership comes from Composition's public registry resolver; no bundled
    ID list is duplicated here.  A source-backed descriptor keeps the normal
    renderability result, and an unknown source-less rendering descriptor is
    supported only when Composition actually publishes that ID.
    """
    public_ids = _public_registry_ids()
    projected: list[dict[str, object]] = []
    for descriptor in descriptors:
        renderability = descriptor.get("renderability")
        kind = descriptor.get("kind")
        element_id = descriptor.get("id")
        if (
            descriptor.get("source") == "pack:rendering"
            and isinstance(renderability, dict)
            and renderability.get("preview") == "unknown"
        ):
            if not isinstance(kind, str) or not isinstance(element_id, str):
                raise ValueError(
                    "Cannot generate an incomplete element catalog: invalid "
                    "rendering descriptor identity"
                )
            if element_id not in public_ids.get(f"{kind}s", frozenset()):
                raise ValueError(
                    f"Cannot generate an incomplete element catalog: rendering "
                    f"element {kind}/{element_id} has no component and is not "
                    "supplied by Composition's public registry"
                )
            descriptor = {
                **descriptor,
                "renderability": {
                    "preview": "supported",
                    "browserExport": "supported",
                    "workerExport": "supported",
                },
            }
        projected.append(descriptor)
    return tuple(projected)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the checked-in projection differs from generated output",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    expected = generate()
    output = args.output.resolve()
    actual = output.read_text(encoding="utf-8") if output.is_file() else None
    if args.check:
        if actual != expected:
            print(f"{output} is stale; run scripts/gen_element_catalog.py", file=sys.stderr)
            return 1
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

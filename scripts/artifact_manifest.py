"""Generate or check artifacts.json: the digest of every file consumers copy or rely on.

    python scripts/artifact_manifest.py          # rewrite the manifest
    python scripts/artifact_manifest.py --check  # exit 1, naming each changed path

Consumers: astrid-app vendors the browser file set below into vendor/astrid-browser (its config/astrid-vendor-files.json
declares the same set) and the tool catalog's bound pack files; cli-surface.json is generated by gen_cli_surface.py.
astrid_runtime_client/ is a copy Astrid RECEIVES from the Runtime, so it is not an Astrid artifact.
"""


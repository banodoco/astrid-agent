def _bound_pack_files(root: Path) -> set[Path]:
    """The pack files each tool in the catalog binds (manifest, entry, resources)."""
    try:
        tools = json.loads((root / TOOL_CATALOG).read_text(encoding="utf-8"))["tools"]
    except (OSError, ValueError, KeyError):
        return set()
    bound = set()
    for tool in tools:
        for ref in [tool["manifest"], tool["entry"], *tool.get("resources", [])]:
            bound.add(root / "astrid" / "packs" / tool["pack_id"] / ref["path"])
    return bound


def digests(root: Path = ROOT, patterns: list[str] = PATTERNS) -> dict[str, str]:
    paths = {p for pattern in patterns for p in root.glob(pattern) if p.is_file()} | {p for p in _bound_pack_files(root) if p.is_file()}
    return {p.relative_to(root).as_posix(): "sha256:" + hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)}


def build(root: Path = ROOT, patterns: list[str] = PATTERNS) -> dict:
    artifacts = digests(root, patterns)
    canonical = json.dumps(artifacts, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return {"producer": PRODUCER, "version": "sha256:" + hashlib.sha256(canonical).hexdigest(), "artifacts": artifacts}


def write(root: Path = ROOT, patterns: list[str] = PATTERNS) -> dict:
    manifest = build(root, patterns)
    (root / MANIFEST).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return manifest


def check(root: Path = ROOT, patterns: list[str] = PATTERNS) -> list[str]:
    """Return one line per artifact whose digest changed, appeared or disappeared."""
    try:
        committed = json.loads((root / MANIFEST).read_text(encoding="utf-8"))["artifacts"]
    except (OSError, ValueError, KeyError):
        return [f"{MANIFEST}: missing or unreadable"]
    current = digests(root, patterns)
    problems = [f"{path}: " + ("added" if path not in committed else "removed" if path not in current else "changed")
                for path in sorted(committed.keys() | current.keys()) if committed.get(path) != current.get(path)]
    if not problems and json.loads((root / MANIFEST).read_text(encoding="utf-8")) != build(root, patterns):
        problems.append(f"{MANIFEST}: version does not match its artifacts")
    return problems


def main(argv: list[str]) -> int:
    if "--check" in argv:
        problems = check()
        if problems:
            print("artifact manifest is stale; run `python scripts/artifact_manifest.py`:\n  " + "\n  ".join(problems))
            return 1
        print(f"{MANIFEST} is current")
        return 0
    manifest = write()
    print(f"wrote {MANIFEST}: {len(manifest['artifacts'])} artifacts, {manifest['version']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

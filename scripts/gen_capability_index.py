#!/usr/bin/env python3
"""Generate the capability catalog for the Astrid skills.

Lists every executor, orchestrator, and element of the packs that ship in this
repo (``astrid/packs/``) with its short_description, so agents can discover
what is available without grepping manifests. External packs (managed
sources, ``ASTRID_PACKS_PATH``) are never listed: the catalog is committed, so
it must not depend on the machine that generated it. They stay discoverable
live through ``astrid skills`` and ``discover``. Idempotent: re-running with no
manifest changes leaves the file byte-identical.

Pass --target to write only the specified file (for testing).
"""

from __future__ import annotations

import argparse
import contextlib
import os
import sys
import tempfile
from collections.abc import Iterator
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from astrid.core.element.registry import load_default_registry as load_elements  # noqa: E402
from astrid.core.execution.executor.registry import load_default_registry as load_executors  # noqa: E402
from astrid.core.execution.orchestrator.registry import (  # noqa: E402
    load_default_registry as load_orchestrators,
)
from astrid.core.search import short_description_or_truncated  # noqa: E402
from astrid.core.foundation.paths import REPO_ROOT as ASTRID_REPO_ROOT  # noqa: E402

PACKS_ROOT = (REPO_ROOT / "astrid/packs").resolve()
CAPABILITY_INDEX_PATH = REPO_ROOT / "astrid/packs/_core/docs/references/capabilities.md"

BEGIN_MARKER = "<!-- BEGIN CAPABILITY INDEX (auto-generated by scripts/gen_capability_index.py) -->"
END_MARKER = "<!-- END CAPABILITY INDEX -->"


def _row(identifier: str, short: str) -> str:
    cleaned = short.replace("|", "\\|")
    return f"| `{identifier}` | {cleaned} |"


def _section(title: str, items: list[tuple[str, str]]) -> list[str]:
    lines = [f"### {title}", "", "| id | short_description |", "| --- | --- |"]
    if not items:
        lines.append("| _(none)_ | |")
    else:
        for identifier, short in sorted(items, key=lambda pair: pair[0]):
            lines.append(_row(identifier, short or "_(no description)_"))
    lines.append("")
    return lines


def _in_repo_pack(root: object) -> bool:
    """True when *root* lies under ``astrid/packs/`` of this checkout."""
    if not root:
        return False
    try:
        Path(str(root)).resolve().relative_to(PACKS_ROOT)
    except ValueError:
        return False
    return True


@contextlib.contextmanager
def _in_repo_packs_only() -> Iterator[None]:
    """Hide every external pack source from discovery while the registries load.

    Unsets ``ASTRID_PACKS_PATH`` and points ``ASTRID_HOME`` and the managed
    pack-source state/data at an empty temp dir, so a broken or newer external
    pack on this machine can neither appear in nor break the catalog.
    """
    from astrid.core.pack.discovery import ASTRID_PACKS_PATH_ENV
    from astrid.core.pack.source_setup import SOURCE_DATA_ENV, SOURCE_STATE_ENV

    overrides: dict[str, str | None] = {ASTRID_PACKS_PATH_ENV: None}
    saved = {name: os.environ.get(name) for name in (ASTRID_PACKS_PATH_ENV, "ASTRID_HOME", SOURCE_STATE_ENV, SOURCE_DATA_ENV)}
    with tempfile.TemporaryDirectory(prefix="astrid-capability-index-") as empty:
        overrides.update(
            {
                "ASTRID_HOME": empty,
                SOURCE_STATE_ENV: str(Path(empty) / "pack-sources.json"),
                SOURCE_DATA_ENV: str(Path(empty) / "packs"),
            }
        )
        try:
            for name, value in overrides.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value
            yield
        finally:
            for name, value in saved.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value


def _executor_rows() -> list[tuple[str, str]]:
    registry = load_executors()
    return [
        (executor.id, short_description_or_truncated(executor.short_description, executor.description))
        for executor in registry.list()
        if _in_repo_pack(executor.metadata.get("pack_root"))
    ]


def _orchestrator_rows() -> list[tuple[str, str]]:
    registry = load_orchestrators()
    return [
        (orchestrator.id, short_description_or_truncated(orchestrator.short_description, orchestrator.description))
        for orchestrator in registry.list()
        if _in_repo_pack(orchestrator.metadata.get("pack_root"))
    ]


def _element_rows() -> list[tuple[str, str]]:
    registry = load_elements(project_root=ASTRID_REPO_ROOT)
    return [
        (
            f"{element.kind}/{element.id}",
            short_description_or_truncated(element.short_description, element.description),
        )
        for element in registry.list()
        if _in_repo_pack(element.root)
    ]


def render_block() -> str:
    lines = [BEGIN_MARKER, ""]
    with _in_repo_packs_only():
        lines.extend(_section("Executors", _executor_rows()))
        lines.extend(_section("Orchestrators", _orchestrator_rows()))
        lines.extend(_section("Elements", _element_rows()))
    lines.append(END_MARKER)
    return "\n".join(lines)


def update_skill(text: str, block: str) -> str:
    if BEGIN_MARKER in text and END_MARKER in text:
        before, _, rest = text.partition(BEGIN_MARKER)
        _, _, after = rest.partition(END_MARKER)
        return f"{before}{block}{after}"
    # Insert before the "## Make something new" heading if present, otherwise
    # append to the end with a leading blank line.
    anchor = "## Make something new"
    if anchor in text:
        before, _, after = text.partition(anchor)
        return f"{before}{block}\n\n{anchor}{after}"
    suffix = "" if text.endswith("\n") else "\n"
    return f"{text}{suffix}\n{block}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--target",
        type=Path,
        default=None,
        help="Write only to the specified file (bypasses deduplication).",
    )
    args = parser.parse_args()

    block = render_block()

    targets = [args.target if args.target is not None else CAPABILITY_INDEX_PATH]

    any_updated = False
    for path in targets:
        if not path.exists():
            # Create the file with empty content if it doesn't exist
            current = ""
        else:
            current = path.read_text(encoding="utf-8")
        updated = update_skill(current, block)
        if updated != current:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(updated, encoding="utf-8")
            print(f"updated {path}")
            any_updated = True
        else:
            print(f"unchanged {path}")
    return 0 if any_updated else 0


if __name__ == "__main__":
    raise SystemExit(main())

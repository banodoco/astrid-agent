#!/usr/bin/env python3
"""Evaluate CP1 source and installed identity; inputs and installer evidence are trusted.

Read repository bytes from immutable Git objects, never from a working tree. See
--help for inputs. A passing receipt is compatible with C-06's local evaluator.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

CP1 = {'runtime': '3b12fface79a3be029f3b6623765a7f3e1e5e24f',
       'agent': '0a47bf37e309741ef2a90d18739fa94758cf8f3f',
       'app': '8a05d31ae702ad83d8e61867d82f0fc2feb52ce3',
       'pinokio': '8d8e1b46948f6a0cdf8d3f81f4db3f14c21f11b2'}
COMPOSITION = 'cdd89c78d18b4b437a03efd1fff081f1ce00ee448d644ef8360fc1937df60f0f'
EXCEPTIONS = {'runtime.lock.json': '446e12ef4639b7b1b84f86d51dc5fb3320bd3a3dabff5e661b8f5be26ffef8b9',
              'public/install-manifest.json': 'fe12781e4da60d441595c08f84cb8d0390d840ab7c71227b8c4eff791553795e'}
SHA = re.compile(r'^[0-9a-f]{40}$')
HASH = re.compile(r'^sha256:[0-9a-f]{64}$')


def digest(data):
    return hashlib.sha256(data).hexdigest()


def tuple_digest(tup):
    return digest(json.dumps({k: v for k, v in tup.items() if k != 'digest'}, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode())


def git(repo, *args):
    return subprocess.run(['git', '-C', str(repo), *args], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout


def read_git(repos, name, path):
    # Reject ambiguous Git revision/path syntax and traversal in metadata.
    if not isinstance(path, str) or not path or path.startswith('/') or any(p in ('', '.', '..') for p in path.split('/')) or ':' in path or '\\' in path:
        raise ValueError('invalid repository path: ' + repr(path))
    return git(repos[name], 'show', CP1[name] + ':' + path)


def evaluate(tup, schema, repos, installed_manifest, installed_vibe, installed_composition):
    """Return receipt. Errors fail closed; expected findings are never called fresh."""
    errors, expected = [], []
    identity = tuple_digest(tup)
    result = {'check': 'C-07', 'result': 'fail', 'tuple_digest': identity,
              'repo_shas': CP1.copy(), 'errors': errors, 'expected_findings': expected}
    try:
        import jsonschema
        jsonschema.Draft202012Validator.check_schema(schema)
        jsonschema.Draft202012Validator(schema, format_checker=jsonschema.FormatChecker()).validate(tup)
        if set(tup['repos']) != set(CP1) or any(tup['repos'][r]['sha'] != sha or tup['repos'][r]['url'] != 'https://github.com/banodoco/astrid-' + r for r, sha in CP1.items()):
            raise ValueError('tuple is not the published four-repository CP1')
        if 'digest' in tup and tup['digest'] != identity:
            raise ValueError('tuple digest mismatch')
        for repo, sha in CP1.items():
            git(repos[repo], 'cat-file', '-e', sha + '^{commit}')

        def get(repo, path):
            return read_git(repos, repo, path)

        def check_lock(consumer, lock_path, producer, expected_source, accepted=False):
            raw = get(consumer, lock_path)
            lock = json.loads(raw)
            files = lock.get('files')
            if not isinstance(files, dict) or not files:
                raise ValueError(consumer + ' ' + lock_path + ': empty files')
            exception = accepted and digest(raw) == EXCEPTIONS[lock_path]
            if lock.get('source_commit') != expected_source:
                msg = f'{consumer} {lock_path}: source_commit {lock.get("source_commit")} != tuple {expected_source}'
                (expected if exception else errors).append(msg + (' (CP1 I-AP-07 exception; stale)' if exception else ''))
            # Always validate consumer bytes even for the accepted stale lock.
            for path, entry in files.items():
                if not isinstance(entry, dict) or not isinstance(entry.get('sha256'), str) or not HASH.fullmatch(entry['sha256']):
                    raise ValueError(f'{consumer} {lock_path}: invalid entry {path}')
                if 'sha256:' + digest(get(consumer, path)) != entry['sha256']:
                    errors.append(f'{consumer} {path}: stale generated bytes')
            if exception:
                return
            manifest_path = lock.get('manifest')
            manifest = json.loads(get(producer, manifest_path))
            if lock.get('producer') != 'astrid-' + producer or manifest.get('producer') != lock.get('producer') or lock.get('producer_version') != manifest.get('version') or not isinstance(manifest.get('artifacts'), dict):
                errors.append(f'{consumer} {lock_path}: producer manifest identity/version mismatch')
                return
            for path, entry in files.items():
                source = entry.get('from')
                actual = 'sha256:' + digest(get(producer, source))
                if actual != entry['sha256'] or manifest['artifacts'].get(source) != actual:
                    errors.append(f'{consumer} {path}: producer/consumer bytes or manifest differ')

        for consumer, path, producer, accepted in [
            ('agent', 'runtime.lock.json', 'runtime', False),
            ('app', 'runtime.lock.json', 'runtime', True),
            ('app', 'config/astrid-cli-surface/vendor.lock.json', 'agent', False),
        ]:
            try:
                check_lock(consumer, path, producer, CP1[producer], accepted)
            except (ValueError, TypeError, KeyError, OSError, subprocess.CalledProcessError) as exc:
                errors.append(f'{consumer} {path}: evidence unavailable or invalid: {exc}')
        raw = get('app', 'public/install-manifest.json')
        manifest = json.loads(raw)
        for name in ('agent', 'runtime'):
            actual = manifest.get(name, {}).get('sha')
            if actual != CP1[name]:
                msg = f'app install-manifest {name}.sha {actual} != tuple {CP1[name]}'
                (expected if digest(raw) == EXCEPTIONS['public/install-manifest.json'] else errors).append(msg + (' (CP1 I-AP-07 exception; stale)' if digest(raw) == EXCEPTIONS['public/install-manifest.json'] else ''))
        recipe = json.loads(get('agent', 'astrid/packs/vibecomfy/recipe.windows-cu130.json'))
        pins_raw = get('agent', 'astrid/packs/vibecomfy/pins.json')
        if recipe.get('pins') != {'path': 'packs/vibecomfy/pins.json', 'sha256': digest(pins_raw)} or not any(x.get('name') == 'vibecomfy' and x.get('pin') == 'vibecomfy' for x in recipe.get('source_bindings', [])):
            raise ValueError('Agent VibeComfy recipe/pins binding mismatch')
        vibe = json.loads(pins_raw)['sources']['vibecomfy']['revision']
        if not isinstance(vibe, str) or not SHA.fullmatch(vibe):
            raise ValueError('invalid Agent VibeComfy revision')
        installed = json.loads(Path(installed_manifest).read_bytes())
        for name in ('agent', 'runtime'):
            if installed.get(name, {}).get('sha') != CP1[name]:
                errors.append(f'installed manifest {name}.sha differs from tuple {CP1[name]}')
        if installed.get('vibecomfy', {}).get('sha') != vibe:
            errors.append(f'installed manifest VibeComfy differs from Agent pin {vibe}')
        actual_vibe = git(installed_vibe, 'rev-parse', 'HEAD').decode().strip()
        if actual_vibe != vibe or git(installed_vibe, 'status', '--porcelain', '--untracked-files=all').strip():
            errors.append(f'installed VibeComfy checkout differs from Agent pin {vibe} or is dirty')
        if digest(Path(installed_composition).read_bytes()) != COMPOSITION:
            errors.append('installed composition archive digest differs from T-06')
        for repo, path in [('agent', 'remotion/artifacts/banodoco-timeline-composition-0.0.17.tgz'), ('app', 'vendor/artifacts/banodoco-timeline-composition-0.0.17.tgz')]:
            try:
                if digest(get(repo, path)) != COMPOSITION:
                    errors.append(f'{repo} composition archive digest differs from T-06')
            except (OSError, subprocess.CalledProcessError):
                errors.append(f'{repo} composition archive missing')
    except (ValueError, TypeError, KeyError, OSError, subprocess.CalledProcessError, ImportError) as exc:
        errors.append(f'evidence unavailable or invalid: {type(exc).__name__}: {exc}')
    except Exception as exc:
        # Includes jsonschema validation errors; unexpected evidence is never green.
        errors.append(f'evidence invalid: {type(exc).__name__}: {exc}')
    if not errors:
        result['result'] = 'pass'
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('tuple', 'schema', 'runtime', 'agent', 'app', 'pinokio', 'installed-manifest', 'installed-vibe', 'installed-composition'):
        parser.add_argument('--' + name, required=True, type=Path)
    args = parser.parse_args()
    try:
        receipt = evaluate(json.loads(args.tuple.read_bytes()), json.loads(args.schema.read_bytes()), {r: getattr(args, r) for r in CP1}, args.installed_manifest, args.installed_vibe, args.installed_composition)
    except Exception as exc:
        receipt = {'check': 'C-07', 'result': 'fail', 'errors': [f'input unavailable or invalid: {exc}']}
    print(json.dumps(receipt, indent=2, sort_keys=True))
    return 0 if receipt['result'] == 'pass' else 1


if __name__ == '__main__':
    raise SystemExit(main())

"""Generate motion primitives, following the gen_audio_curves source workflow.

The registry selects fixed families, never expressions. Pass --composition-root
to emit the identical TypeScript primitive into the shared renderer checkout.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from pprint import pformat

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "astrid/core/timeline/motion_curves.json"
PYTHON = ROOT / "astrid/core/timeline/motion_curves.py"
TYPESCRIPT = ROOT / "astrid/core/timeline/motion_curves.generated.ts"


def render() -> tuple[str, str]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if data.get("version") != 1:
        raise ValueError("unsupported motion curve declaration")
    curves = data["curves"]
    families = {"linear", "quadratic-in", "quadratic-out", "quadratic-in-out", "hold-until-end"}
    aliases = {}
    for name, spec in curves.items():
        if spec["family"] not in families or spec["inverse"] != (spec["family"] != "hold-until-end"):
            raise ValueError(f"unsupported motion family or inverse: {name}")
        for alias in [name, *spec["aliases"]]:
            key = alias.strip().lower()
            if key in aliases and aliases[key] != name:
                raise ValueError(f"ambiguous motion alias: {alias}")
            aliases[key] = name
    py = '''# Generated by scripts/gen_motion_curves.py; edit motion_curves.json.
from __future__ import annotations

import math

MOTION_CURVES = REGISTRY
_ALIASES = ALIASES


def motion_curve_name(value: str) -> str:
    try:
        return _ALIASES[value.strip().lower()]
    except (KeyError, AttributeError):
        raise ValueError(f"unknown motion easing {value!r}") from None


def _unit(value: float) -> float:
    if not math.isfinite(value):
        raise ValueError("motion progress must be finite")
    return min(1.0, max(0.0, value))


def motion_curve_progress(name: str, progress: float) -> float:
    family = MOTION_CURVES[motion_curve_name(name)]["family"]
    u = _unit(progress)
    if u == 0 or u == 1:
        return u
    if family == "linear":
        return u
    if family == "quadratic-in":
        return u * u
    if family == "quadratic-out":
        return 1 - (1 - u) * (1 - u)
    if family == "quadratic-in-out":
        return 2 * u * u if u < 0.5 else 1 - 2 * (1 - u) * (1 - u)
    return 0.0


def motion_curve_inverse(name: str, progress: float) -> float:
    spec = MOTION_CURVES[motion_curve_name(name)]
    p = _unit(progress)
    if not spec["inverse"]:
        raise ValueError("motion easing 'step' has no inverse progress")
    if p == 0 or p == 1:
        return p
    family = spec["family"]
    if family == "linear":
        return p
    if family == "quadratic-in":
        return math.sqrt(p)
    if family == "quadratic-out":
        return 1 - math.sqrt(1 - p)
    return math.sqrt(p / 2) if p < 0.5 else 1 - math.sqrt((1 - p) / 2)
'''.replace("REGISTRY", pformat(curves, sort_dicts=False)).replace("ALIASES\n", pformat(aliases, sort_dicts=False) + "\n")
    ts = '''// Generated by scripts/gen_motion_curves.py; edit motion_curves.json.
export const MOTION_CURVES = REGISTRY as const;
export type MotionCurveName = keyof typeof MOTION_CURVES;
const aliases: Readonly<Record<string, MotionCurveName>> = ALIASES;

export function motionCurveName(value: string): MotionCurveName {
  const key = typeof value === 'string' ? value.trim().toLowerCase() : '';
  const name = Object.prototype.hasOwnProperty.call(aliases, key) ? aliases[key] : undefined;
  if (!name) throw new Error(`unknown motion easing ${String(value)}`);
  return name;
}

function unit(value: number): number {
  if (!Number.isFinite(value)) throw new Error('motion progress must be finite');
  return Math.min(1, Math.max(0, value));
}

export function motionCurveProgress(name: string, progress: number): number {
  const family = MOTION_CURVES[motionCurveName(name)].family;
  const u = unit(progress);
  if (u === 0 || u === 1) return u;
  if (family === 'linear') return u;
  if (family === 'quadratic-in') return u * u;
  if (family === 'quadratic-out') return 1 - (1 - u) * (1 - u);
  if (family === 'quadratic-in-out') return u < 0.5 ? 2 * u * u : 1 - 2 * (1 - u) * (1 - u);
  return 0;
}

export function motionCurveInverse(name: string, progress: number): number {
  const spec = MOTION_CURVES[motionCurveName(name)];
  const p = unit(progress);
  if (!spec.inverse) throw new Error("motion easing 'step' has no inverse progress");
  if (p === 0 || p === 1) return p;
  if (spec.family === 'linear') return p;
  if (spec.family === 'quadratic-in') return Math.sqrt(p);
  if (spec.family === 'quadratic-out') return 1 - Math.sqrt(1 - p);
  return p < 0.5 ? Math.sqrt(p / 2) : 1 - Math.sqrt((1 - p) / 2);
}
'''.replace("REGISTRY", json.dumps(curves, indent=2)).replace("ALIASES", json.dumps(aliases, indent=2))
    return py, ts


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--composition-root", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    py, ts = render()
    outputs = [(PYTHON, py), (TYPESCRIPT, ts)]
    if args.composition_root:
        outputs.append((args.composition_root / "typescript/src/lib/motion-curves.generated.ts", ts))
    for path, content in outputs:
        if args.check:
            if path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"generated motion curve drift: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()

"""Generate a canonical, same-pins next-release install manifest for update tests."""

from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
import json
from collections.abc import Mapping
from pathlib import Path
import sys
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from astrid.core.generation.vibecomfy_dependency import VIBECOMFY_ENGINE_REVISION

DEFAULT_MARKER = "M-RT UPDATE TEST STAND-IN"


def make_standin_release(
    candidate: Mapping[str, Any], *, marker: str = DEFAULT_MARKER
) -> dict[str, Any]:
    """Return a next-release manifest without changing any candidate pins."""
    if not isinstance(candidate, Mapping):
        raise TypeError("candidate manifest must be a mapping")
    release = candidate.get("release")
    if isinstance(release, bool) or not isinstance(release, int) or release < 0:
        raise ValueError("candidate release must be a non-negative integer")
    if not isinstance(marker, str) or not marker.strip():
        raise ValueError("marker must be a non-empty string")

    stand_in = deepcopy(dict(candidate))
    stand_in["release"] = release + 1
    stand_in["qualification_marker"] = marker
    # The installer adds this effective source pin when older manifests omit it.
    # Recording it here makes the generated bytes stable through installation.
    stand_in["vibecomfy"] = candidate.get(
        "vibecomfy", {"sha": VIBECOMFY_ENGINE_REVISION}
    )
    return stand_in


def canonical_manifest_bytes(manifest: Mapping[str, Any]) -> bytes:
    """Match the installer's canonical manifest writer exactly."""
    return (json.dumps(dict(manifest), indent=2, sort_keys=True) + "\n").encode("utf-8")


def _main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("candidate", type=Path, help="candidate App install manifest JSON")
    parser.add_argument("--output", type=Path, required=True, help="generated manifest path")
    parser.add_argument("--sums", type=Path, help="SHA256SUMS output (default: sibling SHA256SUMS)")
    parser.add_argument("--marker", default=DEFAULT_MARKER, help="qualification_marker value")
    args = parser.parse_args()

    candidate = json.loads(args.candidate.read_text(encoding="utf-8"))
    manifest = make_standin_release(candidate, marker=args.marker)
    raw = canonical_manifest_bytes(manifest)
    digest = hashlib.sha256(raw).hexdigest()
    sums_path = args.sums or args.output.with_name("SHA256SUMS")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    sums_path.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(raw)
    sums_path.write_text(f"{digest}  {args.output.name}\n", encoding="utf-8")
    print(digest)
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
